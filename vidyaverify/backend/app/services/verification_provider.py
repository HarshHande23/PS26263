"""
APAAR Verification Provider Interface & Mock Implementation.

This module provides a provider-independent verification architecture.
The application NEVER assumes access to a real government API or AICTE production service.
All simulated results are clearly marked with 'is_simulated = True' and
disclaimers emphasizing prototype status.
"""

import abc
import os
import random
import time
from typing import Dict, Any, Optional
from dataclasses import dataclass
from app.core.enums import VerificationStatus
from app.services.validation_engine import APAAR_PATTERN


@dataclass
class VerificationResult:
    status: VerificationStatus
    is_simulated: bool
    provider_name: str
    response_code: str
    response_message: str
    disclaimer: str
    matched_identity_confidence: Optional[str] = None
    verification_timestamp: Optional[str] = None
    metadata: Optional[Dict[str, Any]] = None


class VerificationProviderInterface(abc.ABC):
    """
    Abstract interface for APAAR Identity Verification.
    Allows seamlessly swapping the simulated test adapter for an authorized
    government or sandbox gateway in future phases without touching core logic.
    """

    @abc.abstractmethod
    def verify_apaar(
        self,
        apaar_id: str,
        student_name: Optional[str] = None,
        date_of_birth: Optional[str] = None,
        simulate_failure_mode: Optional[str] = None,
    ) -> VerificationResult:
        """
        Verify the given APAAR ID against the provider.
        """
        pass


class MockApaarVerificationProvider(VerificationProviderInterface):
    """
    High-fidelity Mock Provider for Hackathon Demonstrations.
    Uses synthetic rules and deterministic test cases to simulate all real-world
    external verification edge cases:
      - 200 SUCCESS (Simulated match)
      - 404 NOT_FOUND (Identifier unknown to repository)
      - 400 INVALID_FORMAT (Malformed identifier)
      - 503 SERVICE_UNAVAILABLE (External gateway downtime)
      - 504 TIMEOUT (Network latency threshold exceeded)
      - 300 MANUAL_REVIEW_REQUIRED (Name / DOB mismatch requiring human adjudication)
    """

    def __init__(self):
        self.provider_mode = os.getenv("APAAR_PROVIDER_MODE", "mock").lower()
        self.endpoint = os.getenv("APAAR_PROVIDER_ENDPOINT", "https://api.mock.vidyaverify.internal/v1/apaar")
        self.api_key = os.getenv("APAAR_PROVIDER_API_KEY", "mock_key_demo_only")

    def verify_apaar(
        self,
        apaar_id: str,
        student_name: Optional[str] = None,
        date_of_birth: Optional[str] = None,
        simulate_failure_mode: Optional[str] = None,
    ) -> VerificationResult:
        clean_apaar = str(apaar_id or "").strip()
        timestamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        disclaimer = "SIMULATED VERIFICATION — Test provider response generated by VidyaVerify prototype. Not an official AICTE or Government of India validation."

        # 1. Check explicit forced failure modes for testing
        if simulate_failure_mode == "timeout":
            return VerificationResult(
                status=VerificationStatus.PROVIDER_UNAVAILABLE,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="GATEWAY_TIMEOUT_504",
                response_message="External APAAR provider timed out after 5000ms. Please retry or verify later.",
                disclaimer=disclaimer,
                verification_timestamp=timestamp,
            )

        if simulate_failure_mode == "unavailable":
            return VerificationResult(
                status=VerificationStatus.PROVIDER_UNAVAILABLE,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="SERVICE_UNAVAILABLE_503",
                response_message="External APAAR provider service is temporarily unreachable (simulated maintenance).",
                disclaimer=disclaimer,
                verification_timestamp=timestamp,
            )

        if simulate_failure_mode == "manual_review":
            return VerificationResult(
                status=VerificationStatus.MANUAL_REVIEW_REQUIRED,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="DISCREPANCY_FLAG_300",
                response_message="Partial match: Identifier exists, but student name or date of birth differs from state records.",
                disclaimer=disclaimer,
                matched_identity_confidence="medium",
                verification_timestamp=timestamp,
            )

        if simulate_failure_mode == "not_found":
            return VerificationResult(
                status=VerificationStatus.NOT_VERIFIED,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="RECORD_NOT_FOUND_404",
                response_message="Identifier not registered in simulated APAAR registry.",
                disclaimer=disclaimer,
                verification_timestamp=timestamp,
            )

        # 2. Syntax/Format validation check
        if not clean_apaar or not APAAR_PATTERN.match(clean_apaar):
            return VerificationResult(
                status=VerificationStatus.NOT_VERIFIED,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="INVALID_IDENTIFIER_FORMAT_400",
                response_message="Identifier does not adhere to 12-digit numeric APAAR standard.",
                disclaimer=disclaimer,
                verification_timestamp=timestamp,
            )

        # 3. Deterministic synthetic routing based on test patterns
        # Test APAARs starting with "0000" simulate NOT FOUND
        if clean_apaar.startswith("0000"):
            return VerificationResult(
                status=VerificationStatus.NOT_VERIFIED,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="RECORD_NOT_FOUND_404",
                response_message="Identifier not registered in simulated APAAR registry.",
                disclaimer=disclaimer,
                verification_timestamp=timestamp,
            )

        # Test APAARs starting with "9999" simulate SERVICE UNAVAILABLE
        if clean_apaar.startswith("9999"):
            return VerificationResult(
                status=VerificationStatus.PROVIDER_UNAVAILABLE,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="SERVICE_UNAVAILABLE_503",
                response_message="Provider connection error during simulated inquiry.",
                disclaimer=disclaimer,
                verification_timestamp=timestamp,
            )

        # Test APAARs starting with "8888" simulate MANUAL REVIEW
        if clean_apaar.startswith("8888"):
            return VerificationResult(
                status=VerificationStatus.MANUAL_REVIEW_REQUIRED,
                is_simulated=True,
                provider_name="Mock APAAR Gateway Adapter",
                response_code="NAME_DOB_MISMATCH_300",
                response_message="Identifier matches record, but student name has typographical variance requiring manual verification.",
                disclaimer=disclaimer,
                matched_identity_confidence="medium",
                verification_timestamp=timestamp,
            )

        # 4. Standard simulated success (Verified by Provider)
        return VerificationResult(
            status=VerificationStatus.VERIFIED_BY_PROVIDER,
            is_simulated=True,
            provider_name="Mock APAAR Gateway Adapter (Synthetic)",
            response_code="MATCH_CONFIRMED_200",
            response_message="Simulated identity confirmation: Identifier verified in synthetic repository.",
            disclaimer=disclaimer,
            matched_identity_confidence="high",
            verification_timestamp=timestamp,
            metadata={"masked_apaar": f"XXXX-XXXX-{clean_apaar[-4:]}", "mode": "synthetic_sandbox"},
        )


def get_verification_provider() -> VerificationProviderInterface:
    """Factory function returning the active verification provider."""
    # When an official production integration is configured, instantiate LiveProvider here.
    return MockApaarVerificationProvider()


# Global singleton provider instance
verification_provider = get_verification_provider()
