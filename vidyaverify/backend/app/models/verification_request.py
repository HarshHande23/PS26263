import uuid
from datetime import datetime, timezone
from sqlalchemy import Column, String, Boolean, DateTime, ForeignKey, Enum as SAEnum
from sqlalchemy.orm import relationship
from app.core.database import Base, UUID
from app.core.enums import VerificationStatus


class VerificationRequest(Base):
    __tablename__ = "verification_requests"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4, index=True)
    student_id = Column(UUID(as_uuid=True), ForeignKey("students.id"), nullable=False, index=True)
    requested_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=True, index=True)
    request_reference = Column(String(100), unique=True, index=True, nullable=False)
    provider_mode = Column(String(50), default="MOCK_SIMULATED", nullable=False)
    status = Column(SAEnum(VerificationStatus), nullable=False, default=VerificationStatus.NOT_CHECKED)
    is_simulated = Column(Boolean, default=True, nullable=False)
    disclaimer = Column(
        String(255),
        default="SIMULATED VERIFICATION — Generated by VidyaVerify prototype test adapter. Not an official AICTE/APAAR production API response.",
        nullable=False,
    )
    response_code = Column(String(50), nullable=True)
    response_message = Column(String(500), nullable=True)
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)

    student = relationship("Student", back_populates="verification_requests")
    requested_by = relationship("User")

    def __repr__(self):
        return f"<VerificationRequest ref={self.request_reference} status={self.status}>"

